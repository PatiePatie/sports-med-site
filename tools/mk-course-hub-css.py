#!/usr/bin/env python3
"""Build course-hub.css from the approved ib-sehs-lesson.css.

Why generated and not hand-copied: every hand edit to a shared asset gets eaten
by the next rebase. This script is the single source, so the file can be
regenerated and diffed at any time.

What it does:
  * takes the READER + HUB half of ib-sehs-lesson.css (lines 23..1160 and
    2455..2486). The IB interactive-model half (1161..2454) is deliberately
    left out: those are .ns-* / .an-* / .kv-* drawings that only ib-sehs-models
    emits, and g10-bio has its own g10-* model layer.
  * renames the prefix: .ib- -> .ch-, ib-reading -> ch-reading, etc.
  * rebases the reader from a standalone PAGE to a full-screen OVERLAY, so the
    same reader can sit on top of a page that keeps its sidebar and top bar.
    That is the fix for the dead-end found on ib-sehs-learn.html, where the
    hub's "Start lesson" sets #lesson/<code> but the page has no reader shell.

Run from the repository root:
    python3 tools/mk-course-hub-css.py ib-sehs-lesson.css course-hub.css
and commit the regenerated course-hub.css with whatever changed upstream.
"""
