def main():
    src_path, out_path = sys.argv[1], sys.argv[2]
    lines = open(src_path, encoding='utf-8').read().split('\n')
    # 1-indexed inclusive ranges, verified against the section banners in the
    # source file. Asserted here so a re-download of the source cannot silently
    # shift them.
    def grab(a, b):
        return '\n'.join(lines[a - 1:b])

    assert '--rail-h' in grab(13, 21), grab(13, 21)

    # The ranges are FOUND BY THEIR BANNER COMMENTS, never hardcoded. They were
    # hardcoded once and a 3KB addition upstream moved every banner below it —
    # the reader block alone slid 2455 -> 2546 — so the extraction silently
    # grabbed the wrong lines while the file still looked plausible.
    def at(needle, nth=0):
        hits = [i for i, l in enumerate(lines) if needle in l]
        assert len(hits) > nth, 'banner not found: %r (%d hits)' % (needle, len(hits))
        return hits[nth]

    BASE      = at('/* ── base ')
    TOK       = at('--rail-h')                     # the geometry token block
    FIGTAB    = at('/* ── figures and tables ')
    FLASH     = at('/* ── flashcard slide ')
    GENFIG    = at('/* ── generated figures ')
    RECEDE    = at('/* ── recede ')
    TAPTGT    = at('/* ── tap targets inside the study guide ')
    FOCUSED   = at('/* ═══ reader as a focused player')
    MODELS    = at('/* ═══ IB SEHS interactive models')
    print('  banners at: base=%d tokens=%d figtab=%d flash=%d genfig=%d recede=%d '
          'taptgt=%d focused=%d models=%d'
          % (BASE + 1, TOK + 1, FIGTAB + 1, FLASH + 1, GENFIG + 1,
             RECEDE + 1, TAPTGT + 1, FOCUSED + 1, MODELS + 1))
    assert TOK < BASE < FIGTAB < FLASH < GENFIG < RECEDE < TAPTGT < FOCUSED, \
        'the banners are not in the order this extraction assumes'

    # Two blocks are IB-only and are dropped on purpose:
    #   "figures and tables"   .ib-fig / .ib-tbl, the reader's own figure and
    #                          table slide renderers. This engine clones the
    #                          course page's real tables instead, so dead.
    #   "generated figures"    the .plate / .lblL / .solid rules that
    #                          ib-sehs-visuals.js draws with. g10 has no .vis-svg.
    # Both reference var(--border) and var(--accent). Those names are UNDEFINED
    # on this site (measured: 76 uses in g10-bio.html, 61 in the theme, all
    # currently inert), and the source file's own `:root{--border:var(--line)}`
    # alias would define them — activating 200+ dormant declarations across the
    # whole site in one move. So the alias goes too and the output is asserted
    # to contain neither name.
    body = grab(BASE, FIGTAB) + grab(FLASH, GENFIG) + grab(RECEDE, TAPTGT)
    # Drop the source's own `--border: var(--line)` alias for the reason above,
    # and repoint the blocks that USED those two names. On the IB page --border
    # was defined as --line and --accent as --gold, so a use of either there is
    # exactly a use of the pair defined here; rewriting the reference keeps those
    # rules correct without ever DEFINING the two names, which is the only thing
    # with a site-wide blast radius. (Upstream added .native-deep, .ib-missing,
    # .ib-defgrp and .ib-tile--toggle after the file this extraction was first
    # written against, and all four name --border.)
    alias = ':root { --border: var(--line); --accent: var(--gold); }'
    assert body.count(alias) == 1, body.count(alias)
    body = body.replace(alias, '')
    body = body.replace('var(--border)', 'var(--line)')
    body = body.replace('var(--accent)', 'var(--gold)')
    # the tail runs to the end of the file; the focused-player block is last
    # (bounded by the IB model CSS that was appended upstream after it)
    END = MODELS if MODELS > FOCUSED else len(lines)
    tail = grab(FOCUSED, END)
    print('  tail = lines %d..%d' % (FOCUSED + 1, END))
    assert 'foot__btn--next' in tail, tail[-400:]
    assert 'IB SEHS interactive models' not in tail, 'the model CSS leaked back in'
    # and it must not drag the IB model layer in from ABOVE
    assert MODELS > TAPTGT, 'model CSS sits before the tap-target block'

    out = body + '\n' + tail + '\n'

    # ORDER MATTERS: the body-scoped rules have to lose their `body.` prefix
    # BEFORE the bare `.ib-` -> `.ch-` rename, or the pattern no longer matches
    # and every one of them silently stays dead (body.ch-lesson never exists).
    for pat, rep in BODY_RULES:
        out = re.sub(pat, rep, out)

    # the six-level scale's two colours go through the guarded pair
    out = out.replace('var(--green)', 'var(--ch-green)').replace('var(--red)', 'var(--ch-red)')

    # rename the prefix
    out = out.replace('.ib-', '.ch-')
    out = out.replace('--ib-c-', '--ch-c-')
    out = out.replace('#ibReader', '#chReader').replace('#ibRead', '#chRead')
    out = out.replace('#ibFoot', '#chFoot').replace('#ibRailToggle', '#chRailToggle')
    out = out.replace('#ibBack', '#chBack').replace('#ibNext', '#chNext')
    out = out.replace('#ibFill', '#chFill').replace('#ibCount', '#chCount')
    out = out.replace('#ibDrill', '#chDrill').replace('#ibExit', '#chExit')
    out = out.replace('#ibLang', '#chLang').replace('#ibDark', '#chDark')
    out = out.replace('#ibScrim', '#chScrim').replace('#ibMap', '#chMap')
    out = out.replace('#ibGloss', '#chGloss').replace('#ibRailClose', '#chRailClose')
    out = out.replace('#ibRailHub', '#chRailHub')

    # The drawer close button: the base `.ch-rail__close{display:none}` sits
    # AFTER the max-width:1039px rule that enables it, at the same specificity,
    # so source order won and the button never rendered on a phone. The source
    # file's own comment describes this bug and then still ships it. Qualifying
    # the in-query selector raises it to (0,2,0) and wins on specificity.
    assert out.count('  .ch-rail__close { display: inline-flex; }') == 1
    out = out.replace('  .ch-rail__close { display: inline-flex; }',
                      '  .ch-lesson .ch-rail__close { display: inline-flex; }')


    out = HEAD + out + TOKENS + EXTRA
    open(out_path, 'w', encoding='utf-8').write(out)

    # post-conditions: no `ib-` may survive, and the two halves must be there.
    txt = open(out_path, encoding='utf-8').read()
    leftover = [l for l in txt.split('\n')
                if 'ib-' in l and 'ib-sehs-lesson.css' not in l]
    assert not leftover, leftover[:6]
    # The whole reason the two dead blocks are dropped: defining --border or
    # --accent here would switch on every `var(--border)` in the site at once.
    # Defining these two at :root would switch on every `var(--border)` in the
    # site at once — 76 dormant uses in g10-bio.html alone, 61 in the theme.
    # A *reference* is fine (rewritten above); a *definition* is not.
    for banned in ['--border:', '--accent:', '.vis-svg']:
        hits = [l for l in txt.split('\n') if banned in l]
        assert not hits, (banned, hits[:4])
    for must in ['--rail-h: 58px', '--r-md: 14px', '--line: var(--border2',
                 '--blue2: #2f6fb5', 'body.dark {', '--ch-green:',
                 '.ch-lesson {', '.ch-hub {', '.ch-tabs {', '.ch-lev {',
                 '.ch-rtile {', '.ch-trow {', '.ch-defcard {', '.ch-blank {',
                 '.ch-foot {', '.ch-top {', '.ch-rail {', '.ch-course {']:
        assert must in txt, must
    print('%s  %d bytes  %d lines' % (out_path, len(txt.encode()), txt.count('\n') + 1))


if __name__ == '__main__':
    main()